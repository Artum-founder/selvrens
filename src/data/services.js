const BY = new Map(LIST.map(([d, n, c, del]) => [d, { domain: d, name: n, category: c, del }]));

const KEYWORDS = [
  [/bank|pay|card|kredit|finans|invest|crypto|coin/, "finance"],
  [/shop|store|butikk|handel|market/, "shopping"],
  [/game|gaming|spill|play/, "gaming"],
  [/mail|cloud|drive/, "email"],
  [/fly|air|hotel|travel|reise|tog|bus/, "travel"],
  [/date|dating|match/, "dating"],
  [/fit|health|helse|run|gym/, "health"],
  [/kommune|\.gov|stat|etat/, "public"],
];

export function lookup(domainOrUrl) {
  const d = domainOf(domainOrUrl);
  const hit = BY.get(d);
  if (hit) return { ...hit, known: true };
  const cat = (KEYWORDS.find(([re]) => re.test(d)) || [null, "other"])[1];
  const label = d ? d.split(".")[0] : "";
  return { domain: d, name: label ? label.charAt(0).toUpperCase() + label.slice(1) : "", category: cat, del: "", known: false };
}

